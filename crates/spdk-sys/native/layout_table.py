"""Writes layout tables for named structures and the enums regenerate.sh constifies in bindings.rs.

Usage: layout_table.py <bindings.rs> <layout.inc> <layout_table.rs> <enum regex>

The C table records the C compiler's sizeof and alignof of each listed type
and offsetof of each named field; the Rust table records size_of, align_of
and offset_of! for the same entries, so the layout test compares the two
compilers' views of one list. An enum earns a row when its alias name matches
the regex, the same pattern bindgen constifies, so every constified enum is
compared with C.
"""
import re
import sys

RUST_KEYWORDS = {"type", "match", "ref", "mod", "fn", "use", "impl", "loop", "move", "box", "where", "priv", "crate", "gen"}

bindings, c_out, rust_out = sys.argv[1:4]
enums = re.compile(sys.argv[4])
try:
    with open(bindings) as source:
        text = source.read()
except OSError as error:
    sys.exit(f"layout_table.py: cannot read {bindings}: {error}")
bodies = {}
kinds = {}
for m in re.finditer(r"pub (struct|union) (\w+)(?:<[^>]*>)? \{\n(.*?)\n\}", text, re.S):
    kinds[m.group(2)] = m.group(1)
    bodies[m.group(2)] = m.group(3)


def fields_of(body, rust_prefix):
    """Yields (Rust field path, C field name) for named fields, descending into anonymous members."""
    for f in re.finditer(r"^    pub (\w+):\s*(\S+)", body, re.M):
        rust_field, ty = f.group(1), f.group(2)
        if rust_field.startswith("__bindgen_anon"):
            inner = bodies.get(ty.rstrip(",").split("::")[-1])
            if inner is not None and "_bindgen_opaque_blob" not in inner:
                yield from fields_of(inner, f"{rust_prefix}{rust_field}.")
            continue
        if rust_field.startswith("_") or "bindgen" in rust_field:
            continue
        c_field = rust_field[:-1] if rust_field.endswith("_") and rust_field[:-1] in RUST_KEYWORDS else rust_field
        yield f"{rust_prefix}{rust_field}", c_field


entries = []
for name, body in bodies.items():
    if "__" in name or name.startswith("_") or "_unused: [u8; 0]" in body or body.strip() == "pub _address: u8,":
        continue
    keyword_ = "union" if kinds[name] == "union" else "struct"
    c_type = name if name.endswith("_t") else f"{keyword_} {name}"
    fields = [] if "_bindgen_opaque_blob" in body else list(fields_of(body, ""))
    entries.append((name, c_type, fields))

for name in re.findall(r"pub type (\w+) = [^;]+;", text):
    if enums.fullmatch(name):
        entries.append((name, f"enum {name}", []))

try:
    with open(c_out, "w") as c:
        c.write("/* Generated by crates/spdk-sys/regenerate.sh from bindings.rs. */\n")
        c.write("static const struct spdk_sys_layout spdk_sys_layouts[] = {\n")
        for name, c_type, fields in entries:
            c.write(f'\t{{"{name}", NULL, sizeof({c_type}), _Alignof({c_type}), 0}},\n')
            for rust_field, c_field in fields:
                c.write(f'\t{{"{name}", "{rust_field}", 0, 0, offsetof({c_type}, {c_field})}},\n')
        c.write("};\n")

    with open(rust_out, "w") as r:
        r.write("// Generated by crates/spdk-sys/regenerate.sh from bindings.rs.\n\n")
        r.write("use core::mem::{align_of, offset_of, size_of};\n\nuse crate::*;\n\n")
        r.write("/// `(type, field, size, align, offset)` entries; type rows have no field.\n")
        r.write("pub(crate) const RUST_LAYOUTS: &[(&str, Option<&str>, usize, usize, usize)] = &[\n")
        for name, _, fields in entries:
            r.write(f'    ("{name}", None, size_of::<{name}>(), align_of::<{name}>(), 0),\n')
            for rust_field, _ in fields:
                r.write(f'    ("{name}", Some("{rust_field}"), 0, 0, offset_of!({name}, {rust_field})),\n')
        r.write("];\n")
except OSError as error:
    sys.exit(f"layout_table.py: cannot write the layout tables: {error}")
