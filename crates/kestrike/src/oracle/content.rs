//! The oracle's generator supplies expected record content, so byte
//! judgments compare delivered copies against test-owned bytes.

use super::ids::{KeyId, Label};

/// Chunk windows of a record: the first window holds `chunk - header`
/// payload bytes and every later window holds `chunk`. The oracle judges
/// bytes only under a geometry that [defines windows](Self::defines_windows).
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub(crate) struct Geometry {
    pub(crate) chunk: usize,
    pub(crate) header: usize,
}

impl Geometry {
    pub(crate) const GOLDEN: Self = Self {
        chunk: 64,
        header: 16,
    };

    /// Whether the geometry has chunk windows: a positive chunk no shorter
    /// than its header.
    pub(crate) fn defines_windows(self) -> bool {
        self.chunk > 0 && self.header <= self.chunk
    }

    /// Payload bytes verified before chunk `index` fails, capped at `total`.
    /// The header comes off the first window before any term saturates, so
    /// an overflowing payload sum yields `total`.
    pub(crate) fn verified_prefix(self, index: u32, total: usize) -> usize {
        match index {
            0 => 0,
            n => self
                .chunk
                .saturating_sub(self.header)
                .saturating_add((n as usize - 1).saturating_mul(self.chunk))
                .min(total),
        }
    }

    /// Whether `len` payload bytes end at a verified chunk boundary short of
    /// a `total`-byte record; a verified whole record is a `Complete` read.
    /// The first window's payload comes off `len` before the divisibility
    /// test, so the arithmetic stays in range for every defined geometry.
    pub(crate) fn is_verified_boundary(self, len: usize, total: usize) -> bool {
        len == 0
            || (len < total
                && len
                    .checked_sub(self.chunk.saturating_sub(self.header))
                    .is_some_and(|rest| rest.is_multiple_of(self.chunk)))
    }
}

/// The label's content as a stream, one byte per step, so a comparison
/// against received fragments holds no generated bytes. The generator's two
/// state words seed from the key and the label separately, so every distinct
/// (key, label) pair over the whole label domain seeds a distinct state, and
/// the key word's constant keeps the state nonzero.
pub(crate) fn expected_stream(key: KeyId, label: Label) -> impl Iterator<Item = u8> {
    let mut s0 = 0x9E37_79B9_7F4A_7C15_u64 ^ u64::from(key.0);
    let mut s1 = 0xBF58_476D_1CE4_E5B9_u64 ^ label.0;
    std::iter::repeat_with(move || {
        let t = s0 ^ (s0 << 23);
        s0 = s1;
        s1 = t ^ s1 ^ (t >> 18) ^ (s1 >> 5);
        (s0.wrapping_add(s1) >> 24) as u8
    })
}

pub(crate) fn expected_bytes(key: KeyId, label: Label, len: usize) -> Vec<u8> {
    expected_stream(key, label).take(len).collect()
}
