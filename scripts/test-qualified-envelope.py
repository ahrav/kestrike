#!/usr/bin/env python3
"""Exercise qualified-envelope.py on a stub install record and bindings, a stub runtime archive, a stub artifact
reference and stub measurements for both enveloped domains."""

import hashlib
import importlib.util
import json
import os
import subprocess
import sys
import tempfile
import unittest
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SCRIPT = ROOT / "scripts/qualified-envelope.py"
SPEC = importlib.util.spec_from_file_location("qualified_envelope", SCRIPT)
assert SPEC is not None and SPEC.loader is not None
envelope = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(envelope)

HEADER = "0" * 63 + "1"
GENERATOR = "0" * 63 + "2"
RECORD = (
    "Target: x86_64-unknown-linux-gnu. Sanitizer: address. Flags: -I/opt/asan/include -Inative\n"
    f"Header digest: {HEADER}\nOutput: cebb931293040bd0\n"
)
BINDINGS = (
    "/* automatically generated by rust-bindgen 0.73.2 */\n\n// Generated by crates/spdk-sys/regenerate.sh.\n"
    f"// Generator digest: {GENERATOR}\n"
    "// bindgen 0.73.2, clang version 15.0.7, rustfmt 1.10.0-stable\n"
)
ASAN_MEASURED = {
    "domain": "asan", "date": "2026-10-16", "host": "stub", "cpus": 4, "memory_mib": 12288,
    "build_seconds": 175, "run_seconds": 61, "build_peak_rss_mib": 3468, "peak_rss_mib": 8815,
}
QEMU_MEASURED = {
    "domain": "qemu", "date": "2026-10-16", "host": {"machine": "x86_64", "runners": ["kestrike-heavy-1", "kestrike-heavy-2"], "accel": "kvm"},
    "guest": {"cpus": 2, "memory_mib": 2048, "backing_mib": 64}, "cpus": 4, "memory_mib": 12288,
    "handshake_seconds": 40, "run_seconds": 30, "build_peak_rss_mib": 3500, "peak_rss_mib": 3000,
}
QEMU_INVENTORY = json.loads((ROOT / "scripts/test-inventory.json").read_text())["qemu"]
NAMESPACE_SECONDS = sum(case["deadline_seconds"] + QEMU_INVENTORY["member_drain_seconds"] for case in QEMU_INVENTORY["namespace_cases"])
PORTABLE = "x86_64-unknown-linux-gnu-x86-64-v2"


def committed(name):
    """Return the target and digests the committed install record `name` and the output it names record."""
    record = envelope.INSTALLS / name
    return envelope.recorded(record, envelope.output_bindings(record))


class QualifiedEnvelope(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix="kestrike-envelope-")
        self.addCleanup(self.temp.cleanup)
        self.dir = Path(self.temp.name)
        self.record = self.dir / "installs" / "x86_64-unknown-linux-gnu-native-asan"
        self.record.parent.mkdir()
        self.record.write_text(RECORD)
        generated = self.dir / "outputs" / "cebb931293040bd0"
        generated.mkdir(parents=True)
        self.bindings = generated / "bindings.rs"
        self.bindings.write_text(BINDINGS)
        self.runtime = self.dir / "librustc-nightly_rt.asan.a"
        self.runtime.write_bytes(b"!<arch>\n")
        self.measurement = self.dir / "measurement.json"
        self.measurement.write_text(json.dumps(ASAN_MEASURED))
        self.qemu_measurement = self.dir / "qemu-measurement.json"
        self.qemu_measurement.write_text(json.dumps(QEMU_MEASURED))
        self.inputs = self.dir / "guest-inputs.env"
        self.inputs.write_text("KESTRIKE_GUEST_QEMU=/usr/bin/qemu-system-x86_64\n")
        self.artifact = self.dir / "artifact.json"
        self.artifact.write_text(json.dumps(self.reference()))
        self.executable = self.dir / "kestrike-0123abcd"
        self.executable.write_bytes(b"\x7fELF test executable")
        self.initrd = self.dir / "guest-initrd.img"
        self.initrd.write_bytes(b"070701 base and appended archives")

    def reference(self, **changes):
        found = committed(PORTABLE)
        reference = {
            "target": found["target"], "rustflags": "-Ctarget-cpu=x86-64-v2", "generated": PORTABLE,
            "header_digest": found["header_digest"], "generator_digest": found["generator_digest"],
            "archives": "a" * 64, "install": "/opt/spdk-v25.05.1-x86-64-v2", "source": "ahrav/kestrike#664 build 12",
        }
        reference.update(changes)
        return reference

    def asan_args(self, **changes):
        values = {
            "record": str(self.record), "bindings": str(self.bindings), "target": "x86_64-unknown-linux-gnu",
            "rustflags": "-Zsanitizer=address -Cforce-frame-pointers=yes", "sanitizer": "address",
            "compilers": "GCC: (GNU) 11.5.0", "configure": "c" * 64, "archives": "a" * 64, "lineage": "unrecorded",
            "runtime": str(self.runtime), "rustc": "rustc 1.99.0-nightly (dc3f85158 2026-07-26)", "llvm": "22.1.8",
            "build_minutes": 15, "run_minutes": 20,
        }
        values.update(changes)
        # The flags open with a dash, so the `=` form keeps argparse from reading them as an option.
        return envelope.parser().parse_args(["asan", *(f"--{name.replace('_', '-')}={value}" for name, value in values.items())])

    def qemu_args(self, **changes):
        values = {
            "artifact": str(self.artifact), "compilers": "GCC: (GNU) 11.5.0", "configure": "c" * 64, "lineage": "unrecorded",
            "host_kernel": "6.12.0", "host_machine": "x86_64", "runner": "kestrike-heavy-1",
            "accel": "kvm", "inputs": str(self.inputs), "executable": str(self.executable), "initrd": str(self.initrd),
            "cpus": 2, "memory_mib": 2048, "backing_mib": 64,
            "handshake_minutes": 5, "run_minutes": 15,
        }
        values.update(changes)
        return envelope.parser().parse_args(["qemu", *(f"--{name.replace('_', '-')}={value}" for name, value in values.items())])

    def test_the_asan_envelope_names_every_qualified_field_from_its_inputs(self):
        written = envelope.envelope(self.asan_args(), environ={"GITHUB_RUN_ATTEMPT": "2", "GITHUB_RUN_ID": "77"}, measurement_file=self.measurement)
        self.assertEqual(written["domain"], "asan")
        self.assertEqual((written["attempt"], written["run"]), ("2", "77"))
        self.assertEqual((written["header_digest"], written["generator_digest"]), (HEADER, GENERATOR))
        self.assertEqual(written["generator"], "bindgen 0.73.2, clang version 15.0.7, rustfmt 1.10.0-stable")
        self.assertEqual((written["install"], written["generated"]), (str(self.record), str(self.bindings.parent)))
        self.assertEqual(written["native"], {"compilers": "GCC: (GNU) 11.5.0", "configure": "c" * 64, "archives": "a" * 64,
                                              "lineage": "unrecorded"})
        self.assertEqual(written["runtime"]["archive"], str(self.runtime))
        self.assertEqual(written["runtime"]["sha256"], hashlib.sha256(b"!<arch>\n").hexdigest())
        self.assertEqual((written["runtime"]["rustc"], written["runtime"]["llvm"]), ("rustc 1.99.0-nightly (dc3f85158 2026-07-26)", "22.1.8"))
        self.assertEqual(written["deadlines"], {"build_minutes": 15, "run_minutes": 20, "build_factor": 4, "run_factor": 10})
        self.assertEqual(written["measured"], ASAN_MEASURED)
        for field in envelope_fields("asan"):
            self.assertTrue(written.get(field), field)

    def test_the_lineage_names_the_record_s_digest_or_unrecorded_and_a_stale_one_is_refused(self):
        self.assertEqual(envelope.envelope(self.asan_args(), environ={}, measurement_file=self.measurement)["native"]["lineage"],
                         "unrecorded", "a record without lineage is unrecorded")
        with self.assertRaisesRegex(envelope.Refusal, "the record is stale"):
            envelope.envelope(self.asan_args(lineage="e" * 64), environ={}, measurement_file=self.measurement)
        with self.assertRaisesRegex(envelope.Refusal, "the record is stale"):
            envelope.envelope(self.qemu_args(lineage="e" * 64), environ={}, measurement_file=self.qemu_measurement)
        Path(self.record).write_text(Path(self.record).read_text() + f"Source: SPDK a DPDK b\nArchive: {'a' * 64}  librte_eal.a\n")
        digest = hashlib.sha256(Path(self.record).read_bytes()).hexdigest()
        written = envelope.envelope(self.asan_args(lineage=digest), environ={}, measurement_file=self.measurement)
        self.assertEqual(written["native"]["lineage"], digest)
        with self.assertRaisesRegex(envelope.Refusal, f"is not {digest}"):
            envelope.envelope(self.asan_args(), environ={}, measurement_file=self.measurement)

    def test_the_qemu_envelope_binds_the_artifact_reference_to_the_committed_record_and_bindings(self):
        written = envelope.envelope(self.qemu_args(), environ={"GITHUB_RUN_ATTEMPT": "3", "GITHUB_RUN_ID": "78"}, measurement_file=self.qemu_measurement)
        found = committed(PORTABLE)
        self.assertEqual((written["domain"], written["attempt"], written["run"]), ("qemu", "3", "78"))
        self.assertEqual(written["target"], found["target"])
        self.assertEqual(written["rustflags"], "-Ctarget-cpu=x86-64-v2")
        record = envelope.INSTALLS / PORTABLE
        self.assertEqual((written["install"], written["generated"]), (str(record), str(envelope.output_bindings(record).parent)))
        self.assertEqual((written["header_digest"], written["generator_digest"]), (found["header_digest"], found["generator_digest"]))
        self.assertEqual(written["generator"], found["generator"])
        self.assertEqual(written["native"], {"compilers": "GCC: (GNU) 11.5.0", "configure": "c" * 64, "archives": "a" * 64,
                                              "lineage": "unrecorded"})
        self.assertEqual(written["artifact"], self.reference())
        self.assertEqual(written["host"], {"kernel": "6.12.0", "machine": "x86_64", "runner": "kestrike-heavy-1", "accel": "kvm"})
        for field, path in (("inputs", self.inputs), ("executable", self.executable), ("initrd", self.initrd)):
            self.assertEqual(written[field], {"path": str(path), "sha256": hashlib.sha256(path.read_bytes()).hexdigest()})
        self.assertEqual(written["deadlines"], {"handshake_minutes": 5, "run_minutes": 15, "handshake_factor": 4, "run_factor": 10})
        self.assertEqual(written["measured"], QEMU_MEASURED)
        for field in envelope_fields("qemu"):
            self.assertTrue(written.get(field), field)

    def test_an_artifact_reference_off_the_committed_records_or_short_a_field_is_refused(self):
        cases = {
            "another digest": (dict(header_digest="f" * 64), "artifact's header_digest"),
            "another target": (dict(target="aarch64-unknown-linux-gnu"), "records another target"),
            "unknown record": (dict(generated="x86_64-unknown-linux-gnu-elsewhere"), "which"),
            "escaping record": (dict(generated="../installs/" + PORTABLE), "names install record"),
            "parent directory": (dict(generated=".."), "names install record"),
            "missing field": (dict(source=""), "lacks ['source']"),
        }
        for name, (changes, text) in cases.items():
            with self.subTest(case=name):
                self.artifact.write_text(json.dumps(self.reference(**changes)))
                with self.assertRaises(envelope.Refusal) as refused:
                    envelope.envelope(self.qemu_args(), environ={}, measurement_file=self.qemu_measurement)
                self.assertIn(text, str(refused.exception))
        self.artifact.write_text("{")
        with self.assertRaises(envelope.Refusal) as refused:
            envelope.envelope(self.qemu_args(), environ={}, measurement_file=self.qemu_measurement)
        self.assertIn("unreadable artifact reference", str(refused.exception))
        self.artifact.write_text(json.dumps(self.reference()))
        for runner in QEMU_MEASURED["host"]["runners"]:
            with self.subTest(registration=runner):
                written = envelope.envelope(self.qemu_args(runner=runner), environ={}, measurement_file=self.qemu_measurement)
                self.assertEqual(written["host"]["runner"], runner)
        for name, changes, text in (
            ("another runner", dict(runner="kestrike-heavy-3"),
             "taken on runners ['kestrike-heavy-1', 'kestrike-heavy-2'], this run is on 'kestrike-heavy-3'"),
            ("another machine", dict(host_machine="aarch64"), "taken on machine 'x86_64', this run is on 'aarch64'"),
            ("another accelerator", dict(accel="tcg"), "taken under accelerator 'kvm', this run is under 'tcg'"),
        ):
            with self.subTest(case=name):
                with self.assertRaises(envelope.Refusal) as refused:
                    envelope.envelope(self.qemu_args(**changes), environ={}, measurement_file=self.qemu_measurement)
                self.assertIn(text, str(refused.exception))
        for name, host in (
            ("not a record", "a workstation"),
            ("single runner field", {"machine": "x86_64", "runner": "kestrike-heavy-1", "accel": "kvm"}),
            ("no accelerator", {"machine": "x86_64", "runners": ["kestrike-heavy-1"]}),
            ("unknown accelerator", {"machine": "x86_64", "runners": ["kestrike-heavy-1"], "accel": "hvf"}),
            ("no runners", {"machine": "x86_64", "runners": [], "accel": "kvm"}),
            ("blank runner", {"machine": "x86_64", "runners": ["kestrike-heavy-1", ""], "accel": "kvm"}),
            ("no machine", {"runners": ["kestrike-heavy-1"], "accel": "kvm"}),
        ):
            with self.subTest(host=name):
                self.qemu_measurement.write_text(json.dumps({**QEMU_MEASURED, "host": host}))
                with self.assertRaises(envelope.Refusal) as refused:
                    envelope.envelope(self.qemu_args(), environ={}, measurement_file=self.qemu_measurement)
                self.assertIn("the guest lane needs a record of its machine, its runner registrations and its accelerator", str(refused.exception))
        self.qemu_measurement.write_text(json.dumps(QEMU_MEASURED))
        self.inputs.unlink()
        with self.assertRaises(envelope.Refusal) as refused:
            envelope.envelope(self.qemu_args(), environ={}, measurement_file=self.qemu_measurement)
        self.assertIn("unreadable", str(refused.exception))

    def test_guest_resources_must_match_a_complete_measured_configuration(self):
        for key, value in (("cpus", 3), ("memory_mib", 4096), ("backing_mib", 128)):
            with self.subTest(resource=key):
                with self.assertRaisesRegex(envelope.Refusal, f"guest {key}.*differs from measured"):
                    envelope.envelope(self.qemu_args(**{key: value}), environ={}, measurement_file=self.qemu_measurement)
        for guest in (None, {}, {"cpus": True, "memory_mib": 2048, "backing_mib": 64},
                      {"cpus": 2, "memory_mib": 0, "backing_mib": 64},
                      {"cpus": 2, "memory_mib": 2048, "backing_mib": 1.5}):
            with self.subTest(measurement=guest):
                self.qemu_measurement.write_text(json.dumps({**QEMU_MEASURED, "guest": guest}))
                with self.assertRaisesRegex(envelope.Refusal, "positive integer guest"):
                    envelope.envelope(self.qemu_args(), environ={}, measurement_file=self.qemu_measurement)

    def test_outside_actions_the_run_and_attempt_are_explicit(self):
        written = envelope.envelope(self.asan_args(), environ={}, measurement_file=self.measurement)
        self.assertEqual((written["attempt"], written["run"]), ("local", "local"))

    def test_a_deadline_below_its_measured_basis_times_its_factor_is_refused(self):
        for name, changes, text in (
            ("build", {"build_minutes": 11}, "the build deadline 11m is below 4 times the measured 175 s (12m)"),
            ("run", {"run_minutes": 10}, "the run deadline 10m is below 10 times the measured 61 s (11m)"),
        ):
            with self.subTest(deadline=name):
                with self.assertRaises(envelope.Refusal) as refused:
                    envelope.envelope(self.asan_args(**changes), environ={}, measurement_file=self.measurement)
                self.assertEqual(str(refused.exception), text)
        for name, changes in (("build", {"build_minutes": 12}), ("run", {"run_minutes": 11})):
            with self.subTest(least=name):
                envelope.envelope(self.asan_args(**changes), environ={}, measurement_file=self.measurement)
        with self.assertRaises(envelope.Refusal) as refused:
            envelope.envelope(self.qemu_args(handshake_minutes=2), environ={}, measurement_file=self.qemu_measurement)
        self.assertEqual(str(refused.exception), "the handshake deadline 2m is below 4 times the measured 40 s (3m)")
        with self.assertRaises(envelope.Refusal) as refused:
            envelope.envelope(self.qemu_args(run_minutes=0), environ={}, measurement_file=self.qemu_measurement)
        self.assertEqual(str(refused.exception), "the run deadline 0m is no positive bound")

    def test_a_record_or_bindings_file_without_a_digest_or_a_missing_runtime_or_measurement_is_refused(self):
        self.bindings.write_text(BINDINGS.replace(f"// Generator digest: {GENERATOR}\n", ""))
        with self.assertRaises(envelope.Refusal) as refused:
            envelope.envelope(self.asan_args(), environ={}, measurement_file=self.measurement)
        self.assertIn("records no generator digest line", str(refused.exception))
        self.bindings.write_text(BINDINGS)
        self.record.write_text(RECORD.replace(f"Header digest: {HEADER}\n", ""))
        with self.assertRaises(envelope.Refusal) as refused:
            envelope.envelope(self.asan_args(), environ={}, measurement_file=self.measurement)
        self.assertIn("records no header digest line", str(refused.exception))
        self.record.write_text(RECORD)
        self.runtime.unlink()
        with self.assertRaises(envelope.Refusal) as refused:
            envelope.envelope(self.asan_args(), environ={}, measurement_file=self.measurement)
        self.assertIn("sanitizer runtime", str(refused.exception))
        self.runtime.write_bytes(b"!<arch>\n")
        for name, edit, text in (
            ("missing figure", lambda m: m.pop("run_seconds"), "the measurement lacks ['run_seconds']"),
            ("foreign domain", lambda m: m.update(domain="qemu"), "the measurement is of domain 'qemu'"),
            ("zero figure", lambda m: m.update(build_seconds=0), "the measurement records build_seconds as 0"),
            ("peak over memory", lambda m: m.update(peak_rss_mib=20000), "exceeds the measured memory 12288 MiB"),
        ):
            with self.subTest(case=name):
                measured = dict(ASAN_MEASURED)
                edit(measured)
                self.measurement.write_text(json.dumps(measured))
                with self.assertRaises(envelope.Refusal) as refused:
                    envelope.envelope(self.asan_args(), environ={}, measurement_file=self.measurement)
                self.assertIn(text, str(refused.exception))
        with self.assertRaises(envelope.Refusal) as refused:
            envelope.envelope(self.qemu_args(), environ={}, measurement_file=self.dir / "absent.json")
        self.assertIn("unreadable measurement", str(refused.exception))

    def test_the_committed_asan_measurement_supports_the_lane_scripts_deadlines(self):
        lane = (ROOT / "scripts/rust-lane.sh").read_text()
        build = int(lane.partition("ASAN_BUILD_MINUTES=")[2].split()[0])
        run = int(lane.partition("ASAN_RUN_MINUTES=")[2].split()[0])
        measured = envelope.measurement(envelope.measurement_path("asan"), "asan")
        deadlines = envelope.deadlines("asan", measured, {"build": build, "run": run})
        self.assertEqual((deadlines["build_minutes"], deadlines["run_minutes"]), (build, run))
        self.assertEqual((measured["cpus"], measured["memory_mib"]), (4, 12288))
        self.assertLess(measured["peak_rss_mib"], measured["memory_mib"])
        self.assertLess(measured["build_peak_rss_mib"], measured["memory_mib"])

    def test_either_peak_over_the_measured_memory_is_refused(self):
        for peak in ("build_peak_rss_mib", "peak_rss_mib"):
            with self.subTest(peak=peak):
                self.measurement.write_text(json.dumps({**ASAN_MEASURED, peak: 20000}))
                with self.assertRaises(envelope.Refusal) as refused:
                    envelope.envelope(self.asan_args(), environ={}, measurement_file=self.measurement)
                self.assertIn("20000 MiB exceeds the measured memory 12288 MiB", str(refused.exception))

    def test_the_committed_qemu_measurement_moves_with_the_pending_job(self):
        """The guest lane stays pending until the CI owner measures it on the runner: without that record the
        envelope refuses to form, so the lane cannot credit from provisional bounds, and the job is in
        PENDING_JOBS; with it the job has left PENDING_JOBS and the record supports the lane script's deadlines."""
        pending = verify_receipts().PENDING_JOBS
        path = envelope.measurement_path("qemu")
        if not path.exists():
            self.assertIn("qemu", pending, "an unmeasured guest lane stays in PENDING_JOBS")
            with self.assertRaises(envelope.Refusal) as refused:
                envelope.envelope(self.qemu_args(), environ={})
            self.assertIn("unreadable measurement", str(refused.exception))
            return
        self.assertNotIn("qemu", pending, "a committed qemu measurement enables the lane; move the job from PENDING_JOBS to HEAVY_JOBS")
        lane = (ROOT / "scripts/rust-lane.sh").read_text()
        minutes = {name: int(lane.partition(f"QEMU_{name.upper()}_MINUTES=")[2].split()[0]) for name in ("handshake", "run")}
        measured = envelope.measurement(path, "qemu")
        deadlines = envelope.deadlines("qemu", measured, minutes)
        self.assertEqual((deadlines["handshake_minutes"], deadlines["run_minutes"]), (minutes["handshake"], minutes["run"]))
        self.assertLess(max(measured["build_peak_rss_mib"], measured["peak_rss_mib"]), measured["memory_mib"])

    def test_the_run_deadline_covers_the_namespace_members_after_the_measured_binder_checks(self):
        """Each namespace member's child dies at its declared deadline, and the wait for its two output pipes ends
        within the inventory's `member_drain_seconds`, so the run deadline is at least the measured binder run times
        the run factor plus each member's declared deadline and drain."""
        least = -(-(QEMU_MEASURED["run_seconds"] * 10 + NAMESPACE_SECONDS) // 60)
        deadlines = sum(case["deadline_seconds"] for case in QEMU_INVENTORY["namespace_cases"])
        self.assertGreater(least, -(-(QEMU_MEASURED["run_seconds"] * 10 + deadlines) // 60), "the members' drains move the bound")
        written = envelope.envelope(self.qemu_args(run_minutes=least), environ={}, measurement_file=self.qemu_measurement)
        self.assertEqual(written["deadlines"]["run_minutes"], least)
        message = (f"the run deadline {least - 1}m is below 10 times the measured {QEMU_MEASURED['run_seconds']} s "
                   f"plus the namespace members' {NAMESPACE_SECONDS} s ({least}m)")
        with self.assertRaises(envelope.Refusal) as refused:
            envelope.envelope(self.qemu_args(run_minutes=least - 1), environ={}, measurement_file=self.qemu_measurement)
        self.assertIn(message, str(refused.exception))

    def test_the_command_writes_json_or_reports_its_refusal(self):
        argv = ["asan", "--record", str(self.record), "--bindings", str(self.bindings), "--target", "x86_64-unknown-linux-gnu",
                "--rustflags=-Zsanitizer=address", "--sanitizer", "address", "--compilers", "GCC",
                "--configure", "c" * 64, "--archives", "a" * 64, "--lineage", "unrecorded", "--runtime", str(self.runtime),
                "--rustc", "rustc (stub)", "--llvm", "22.1.8", "--build-minutes", "15", "--run-minutes", "20"]
        env = {k: v for k, v in os.environ.items() if not k.startswith("GITHUB_")}
        result = subprocess.run([sys.executable, str(SCRIPT), *argv], capture_output=True, text=True, env=env, check=False)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertEqual(json.loads(result.stdout)["attempt"], "local")
        argv[argv.index("--build-minutes") + 1] = "1"
        result = subprocess.run([sys.executable, str(SCRIPT), *argv], capture_output=True, text=True, env=env, check=False)
        self.assertEqual((result.returncode, result.stdout), (1, ""))
        self.assertIn("qualified-envelope: the build deadline 1m is below", result.stderr)


def verify_receipts():
    verify = importlib.util.spec_from_file_location("verify_receipts", ROOT / "scripts/verify-receipts.py")
    module = importlib.util.module_from_spec(verify)
    verify.loader.exec_module(module)
    return module


def envelope_fields(domain):
    module = verify_receipts()
    return (*module.ENVELOPE, *module.ENVELOPED[domain])


if __name__ == "__main__":
    unittest.main()
